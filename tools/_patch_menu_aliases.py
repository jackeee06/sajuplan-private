FP = 'web/mng/src/pages/AllMenus.tsx'
text = open(FP, encoding='utf-8').read()
patched, missed = [], []
for p, adds in ADD.items():
    # path 항목의 첫 aliases 배열([...] 단일레벨). 다음 항목 path 전까지.
    pat = re.compile(r"(path: '" + re.escape(p) + r"',(?:(?!path: ').)*?aliases: \[)([^\]]*)(\])", re.DOTALL)
    m = pat.search(text)
    if not m:
        missed.append(p); continue
    existing = m.group(2).rstrip()
    if existing.endswith(','): existing = existing[:-1]
    newitems = ", ".join("'%s'" % a.replace("'", "\\'") for a in adds)
    repl = m.group(1) + existing + ", " + newitems + m.group(3)
    text = text[:m.start()] + repl + text[m.end():]
    patched.append(p)

open(FP, 'w', encoding='utf-8').write(text)
print("patched %d items" % len(patched))
if missed:
    print("MISSED (aliases 배열 못찾음):", missed)
