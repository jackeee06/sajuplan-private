def set_text(p, text):
    """첫 run 서식 유지하며 단락 텍스트 교체. 줄바꿈(\n)은 break로."""
    runs = p.runs
    if not runs:
        r = p.add_run(); runs = [r]
    parts = text.split('\n')
    runs[0].text = parts[0]
    # 나머지 run 비우기
    for r in runs[1:]:
        r.text = ''
    # 추가 줄은 첫 run에 break+text
    for seg in parts[1:]:
        runs[0].add_break()
        runs[0].add_text(seg)


def del_para(p):
    p._element.getparent().remove(p._element)


