def merge_replace(p):
    full = p.text
    new = full
    for a, b in PAIRS:
        new = new.replace(a, b)
    if new != full:
        set_text(p, new)

# 핵심 교체/삭제 안 된 나머지 단락에만 치환 적용
done = set(NEW.keys())
for i, p in enumerate(body_paras):
    if i in done or i in DEL:
        continue
    merge_replace(p)

