for p in d.paragraphs:
    t = p.text.strip()
    for key, new in REPL:
        if t.startswith(key):
            set_text(p, new)
            t = new
            break

# 전역 잔재/조사 치환
GLOBAL = [
    ("서비스을", "서비스를"),
    ("레슨북 서비스 운영 서비스", "레슨북 서비스 운영"),
    ("어플리케이션 및 레슨북 서비스", "레슨북 서비스"),
    ("운영의 진행단계", "전환의 진행단계"),
    ("전체전환기간", "전체 전환기간"),
]
for p in d.paragraphs:
    t = p.text
    new = t
    for a, b in GLOBAL:
        new = new.replace(a, b)
    if new != t:
        set_text(p, new.strip())

d.save(DST)
