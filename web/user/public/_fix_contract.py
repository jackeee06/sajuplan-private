 ("제 15 조",
  "제 15 조 [각종 자료 및 내용의 관리]\n‘을’은 레슨북 서비스 운영을 위하여 ‘갑’이 제공하는 각종 자료 및 내용을 최초 제공 상태로 유지하여야 하며, 이를 ‘갑’의 허락 없이 타 목적으로 사용하지 아니한다."),
 ("본 계약은 계약서 및 레슨북 서비스 운영 신청서",
  "본 계약은 ‘갑’과 ‘을’이 본 계약서에 서명·날인한 날로부터 유효하다."),
 ("(1) 본 계약에 기재되지 않은 사항은",
  "(1) 본 계약에 기재되지 않은 사항은 본 계약의 별첨 및 특이사항에 따르고, 그에 기재되지 않은 사항은 관련 법령 및 상관습에 따른다."),
