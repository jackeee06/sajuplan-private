 ("(1) ‘갑’은 구축대금의 완납",
  "(1) ‘갑’은 용역대금의 완납과 동시에 ‘을’이 운영·구축한 레슨북 서비스 및 그 결과물의 소유권을 주장할 수 있다."),
 ("(2) ‘갑’은 전환기간 만료전",
  "(2) ‘갑’은 각 전환 단계의 운영 인수 전에 레슨북 서비스를 검증할 권리를 가진다."),
