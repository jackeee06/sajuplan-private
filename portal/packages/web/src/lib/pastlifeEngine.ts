export function buildPastLife(birth: string): PastLife {
  const rng = mulberry32(hashString(`pastlife|${birth}`));
  const st = pickOne(rng, STATUS);
  const personality = pickOne(rng, PERSONALITY);
  const unfinished = pickOne(rng, UNFINISHED);
  const bond = pickOne(rng, BOND);
  const keyword = pickOne(rng, KEYWORD);
  const animal = pickOne(rng, ANIMAL);
  const message = pickOne(rng, MESSAGE);
  const pastScore = 60 + Math.floor(rng() * 40);
  const intro = `당신의 전생은 ${st.era}, ${st.place}에서 살던 '${st.s}'이었어요.`;
  const pastName = pickOne(rng, SURNAME) + pickOne(rng, GIVEN);
  const chronicle = [
    { phase: "유년기", emoji: "🌱", text: pickOne(rng, YOUTH) },
    { phase: "전성기", emoji: "🔥", text: pickOne(rng, PRIME) },
    { phase: "말년", emoji: "🍂", text: pickOne(rng, LATE) },
  ];
  return {
    era: st.era, status: st.s, statusEmoji: st.e, intro,
    personality, place: st.place, unfinished,
    gift: st.gift, lesson: st.lesson, bond,
    animal: animal.a, animalEmoji: animal.e, keyword, message, pastScore,
    pastName, chronicle,
    death: pickOne(rng, DEATH),
    karma: { debt: pickOne(rng, DEBT), blessing: pickOne(rng, BLESSING), pattern: pickOne(rng, PATTERN) },
    guardian: pickOne(rng, GUARDIAN),
    reunion: pickOne(rng, REUNION),
    mission: pickOne(rng, MISSION),
    story: STORY[st.s] ?? [],
  };
}
