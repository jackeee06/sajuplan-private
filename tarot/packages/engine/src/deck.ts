const SUIT_EL: Record<Suit, Element> = {
  wands: '불', cups: '물', swords: '공기', pentacles: '흙',
};

const m = (id: string, num: number, ko: string, en: string, up: TarotMeaning, rev: TarotMeaning): TarotCard => ({
  id, arcana: 'major', element: '영혼', number: num, nameKo: ko, nameEn: en,
  img: `/tarot/${id}.webp`, upright: up, reversed: rev,
});

const c = (suit: Suit, num: number, ko: string, en: string, up: TarotMeaning, rev: TarotMeaning): TarotCard => {
  const id = `${suit}-${String(num).padStart(2, '0')}`;
  return { id, arcana: 'minor', suit, element: SUIT_EL[suit], number: num, nameKo: ko, nameEn: en,
    img: `/tarot/${id}.webp`, upright: up, reversed: rev };
};

